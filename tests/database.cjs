// Real PostgreSQL engine (PGlite WASM); synthetic schema, no customer data.
const { PGlite } = require("@electric-sql/pglite");
const fs = require("node:fs");
const assert = require("node:assert/strict");
(async () => {
  const db = new PGlite();
  await db.exec(`create role anon;create role authenticated;create role service_role;
 create schema storage;create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table public.products(id bigint generated by default as identity primary key,code text unique,price numeric(12,2));`);
  await db.exec(fs.readFileSync("supabase_orders.sql", "utf8"));
  for (const file of [
    "migrations/007_v7.sql",
    "migrations/008_notifications.sql",
  ])
    await db.exec(fs.readFileSync(file, "utf8"));
  // Verify rerun safety.
  for (const file of [
    "migrations/007_v7.sql",
    "migrations/008_notifications.sql",
  ])
    await db.exec(fs.readFileSync(file, "utf8"));
  const dualMigration=fs.readdirSync('supabase/migrations').find(f=>f.endsWith('_manual_dual_prices.sql'));
  await db.exec(fs.readFileSync('supabase/migrations/'+dualMigration,'utf8'));
  const order = {
    order_code: "BR-TEST",
    telegram_user_id: "42",
    telegram_username: "demo",
    telegram_verified: true,
    customer_language: "uz",
    customer_name: "Demo",
    phone: "12345",
    backup_phone: "",
    address: "Demo address",
    comment: "",
    total: 185,
    lookup_token_hash: "hash",
    idempotency_key: "one",
    request_hash: "fingerprint",
  };
  const items = [
    {
      product_code: "BD-000001",
      title: "Shoe",
      image: "",
      size: "42",
      color: "White",
      qty: 1,
      unit_price: 185,
      line_total: 185,
    },
  ];
  const create = async (o = order, it = items) =>
    (
      await db.query(
        "select public.burando_create_order($1::jsonb,$2::jsonb) result",
        [JSON.stringify(o), JSON.stringify(it)],
      )
    ).rows[0].result;
  await create();
  await create();
  assert.equal(
    (await db.query("select count(*)::int n from orders")).rows[0].n,
    1,
    "idempotent order",
  );
  assert.equal(
    (await db.query("select count(*)::int n from order_items")).rows[0].n,
    1,
  );
  await assert.rejects(create({ ...order, lookup_token_hash: "wrong" }));
  await assert.rejects(
    create({ ...order, order_code: "BR-FAIL", idempotency_key: "two" }, [
      { ...items[0], qty: 0 },
    ]),
  );
  assert.equal(
    (await db.query("select count(*)::int n from orders")).rows[0].n,
    1,
    "rollback invalid item",
  );
  const action = async (a, v, token = "hash", reason = "") =>
    (
      await db.query(
        "select burando_payment_action($1,$2,$3,$4,$5,$6,$7) result",
        [
          "BR-TEST",
          v,
          a,
          a === "submit" ? "customer" : "admin-test",
          reason,
          a === "submit" ? "1/receipt.jpg" : "",
          token,
        ],
      )
    ).rows[0].result;
  await assert.rejects(
    db.query("select burando_delivery_action('BR-TEST','shipped_japan')"),
  );
  await assert.rejects(action("paid", 0));
  await assert.rejects(action("submit", 0, "wrong"));
  await action("submit", 0);
  assert.equal(
    (await db.query("select payment_status from orders")).rows[0]
      .payment_status,
    "receipt_submitted",
  );
  await assert.rejects(action("review", 0));
  await action("review", 1);
  await assert.rejects(action("submit", 2));
  await assert.rejects(action("reject", 2));
  await action("reject", 2, "hash", "Unreadable receipt");
  await action("submit", 3);
  await action("review", 4);
  await action("paid", 5);
  await assert.rejects(action("submit", 6));
  await assert.rejects(action("paid", 6));
  assert.equal(
    (await db.query("select payment_status from orders")).rows[0]
      .payment_status,
    "paid",
  );
  assert.equal(
    (await db.query("select order_status from orders")).rows[0].order_status,
    "received",
  );
  await db.query("select burando_delivery_action('BR-TEST','delivered')");
  await assert.rejects(
    db.query("select burando_delivery_action('BR-TEST','in_transit')"),
  );
  assert.equal(
    (await db.query("select count(*)::int n from payment_audit")).rows[0].n,
    6,
  );
  assert.equal(
    (
      await db.query(
        "select public from storage.buckets where id='payment-receipts'",
      )
    ).rows[0].public,
    false,
  );
  const notification = (
    await db.query("select burando_claim_notification() item")
  ).rows[0].item;
  assert.equal(notification.status, "sending");
  assert.equal(notification.attempts, 1);
  assert.equal(
    (
      await db.query(
        "select has_function_privilege('anon','burando_create_order(jsonb,jsonb)','EXECUTE') allowed",
      )
    ).rows[0].allowed,
    false,
  );
  assert.equal(
    (
      await db.query(
        "select has_function_privilege('authenticated','burando_payment_action(text,integer,text,text,text,text,text)','EXECUTE') allowed",
      )
    ).rows[0].allowed,
    false,
  );
  await db.exec("set role anon");
  await assert.rejects(db.query("select * from payment_audit"));
  await db.exec("reset role");
  const dualOrder={...order,order_code:'BR-DUAL',idempotency_key:'dual',total_uzs:1999000};
  const dualItems=[{...items[0],unit_price_uzs:1999000,line_total_uzs:1999000}];
  const createdDual=await create(dualOrder,dualItems);assert.equal(createdDual.total_uzs,1999000);
  await db.exec("insert into products(code,price,price_uzs) values('BD-000001',185,2999000)");
  assert.equal((await db.query("select total_uzs from orders where order_code='BR-DUAL'")).rows[0].total_uzs,'1999000.00','stored order is unaffected by current product price');
  assert.equal((await create(dualOrder,dualItems)).total_uzs,1999000,'idempotent retry keeps snapshot');
  await assert.rejects(create({...dualOrder,order_code:'BR-DUAL-BAD',idempotency_key:'dual-bad',total_uzs:1},dualItems));
  await assert.rejects(db.exec("update products set price_uzs=-1"));
  assert.equal((await db.query("select total_uzs from orders where order_code='BR-TEST'")).rows[0].total_uzs,null,'legacy orders are not repriced');
  await db.close();
  console.log(
    "Database: migrations + rerun, transactions, idempotency, rollback, receipt locks, payment transitions, audit, private bucket, role permissions, outbox PASS",
  );
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
