create or replace function public.burando_queue_order_notice() returns trigger
language plpgsql security invoker set search_path=public as $$
declare msg text; target text; ru boolean;
begin
 ru=new.customer_language='ru';
 if tg_op='INSERT' then
   msg='BURANDO · '||new.order_code||E'\n'||case when ru then 'Заказ создан. Ожидается оплата.' else 'Buyurtma yaratildi. To‘lov kutilmoqda.' end||E'\nUSD '||new.total;
   insert into public.notification_outbox(order_id,audience,message) values(new.id,'admin',msg);
 elsif new.payment_status is distinct from old.payment_status then
   msg='BURANDO · '||new.order_code||E'\n'||case new.payment_status
    when 'receipt_submitted' then case when ru then 'Чек отправлен на проверку.' else 'Chek tekshiruvga yuborildi.' end
