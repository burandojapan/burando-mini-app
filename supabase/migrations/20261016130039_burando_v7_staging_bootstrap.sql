    else case when ru then 'Оплата на проверке.' else 'To‘lov tekshirilmoqda.' end end;
   insert into public.notification_outbox(order_id,audience,message) values(new.id,'admin',msg);
   if new.telegram_verified and new.telegram_user_id<>'' and new.payment_status in ('paid','rejected') then
     insert into public.notification_outbox(order_id,audience,message,telegram_user_id) values(new.id,'customer',msg,new.telegram_user_id);
