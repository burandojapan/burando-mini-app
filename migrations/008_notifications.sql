-- Apply only after 007, after schema review, in staging first.
begin;
alter table public.orders add column if not exists customer_language text not null default 'uz';
create table if not exists public.notification_outbox (
 id bigint generated by default as identity primary key,
 order_id bigint not null references public.orders(id),
 audience text not null check(audience in ('admin','customer')),
 message text not null, telegram_user_id text,
 status text not null default 'pending', attempts integer not null default 0,
 available_at timestamptz not null default now(), lease_until timestamptz,
 last_error text not null default '', created_at timestamptz not null default now()
);
alter table public.notification_outbox enable row level security;
revoke all on public.notification_outbox from anon,authenticated;
grant all on public.notification_outbox to service_role;
grant usage,select on sequence public.notification_outbox_id_seq to service_role;
create or replace function public.burando_queue_order_notice() returns trigger
language plpgsql security definer set search_path=public as $$
declare msg text; target text; ru boolean;
begin
 ru=new.customer_language='ru';
 if tg_op='INSERT' then
   msg='BURANDO · '||new.order_code||E'\n'||case when ru then 'Заказ создан. Ожидается оплата.' else 'Buyurtma yaratildi. To‘lov kutilmoqda.' end||E'\nUSD '||new.total;
   insert into public.notification_outbox(order_id,audience,message) values(new.id,'admin',msg);
 elsif new.payment_status is distinct from old.payment_status then
   msg='BURANDO · '||new.order_code||E'\n'||case new.payment_status
    when 'receipt_submitted' then case when ru then 'Чек отправлен на проверку.' else 'Chek tekshiruvga yuborildi.' end
    when 'paid' then case when ru then 'Поступление оплаты подтверждено администратором.' else 'Pul tushgani admin tomonidan tasdiqlandi.' end
    when 'rejected' then case when ru then 'Чек отклонён. Проверьте заказ в приложении.' else 'Chek rad etildi. Ilovada buyurtmani tekshiring.' end
    else case when ru then 'Оплата на проверке.' else 'To‘lov tekshirilmoqda.' end end;
   insert into public.notification_outbox(order_id,audience,message) values(new.id,'admin',msg);
   if new.telegram_verified and new.telegram_user_id<>'' and new.payment_status in ('paid','rejected') then
     insert into public.notification_outbox(order_id,audience,message,telegram_user_id) values(new.id,'customer',msg,new.telegram_user_id);
   end if;
 elsif new.order_status is distinct from old.order_status and new.telegram_verified and new.telegram_user_id<>'' then
   msg='BURANDO · '||new.order_code||E'\n'||case when ru then 'Статус доставки обновлён. Откройте приложение для просмотра.' else 'Yetkazish holati yangilandi. Tafsilotlar ilovada.' end;
   insert into public.notification_outbox(order_id,audience,message,telegram_user_id) values(new.id,'customer',msg,new.telegram_user_id);
 end if;
 return new;
end $$;
drop trigger if exists burando_order_notices on public.orders;
create trigger burando_order_notices after insert or update on public.orders for each row execute function public.burando_queue_order_notice();

create or replace function public.burando_claim_notification() returns jsonb
language plpgsql security definer set search_path=public as $$
declare item public.notification_outbox;
begin
 select * into item from public.notification_outbox
 where attempts<5 and ((status='pending' and available_at<=now()) or (status='sending' and lease_until<now()))
 order by id for update skip locked limit 1;
 if not found then return null; end if;
 update public.notification_outbox set status='sending',attempts=attempts+1,lease_until=now()+interval '2 minutes' where id=item.id returning * into item;
 return to_jsonb(item);
end $$;
revoke all on function public.burando_queue_order_notice() from public,anon,authenticated;
revoke all on function public.burando_claim_notification() from public,anon,authenticated;
grant execute on function public.burando_claim_notification() to service_role;
commit;
