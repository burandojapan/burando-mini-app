create or replace function public.burando_create_order(p_order jsonb, p_items jsonb)
returns jsonb language plpgsql security invoker set search_path=public as $$
declare saved public.orders; existing public.orders; item jsonb;
begin
 perform pg_advisory_xact_lock(hashtextextended(p_order->>'idempotency_key',0));
 select * into existing from public.orders where idempotency_key=p_order->>'idempotency_key';
 if found then
   if existing.request_hash is distinct from p_order->>'request_hash' or existing.lookup_token_hash is distinct from p_order->>'lookup_token_hash' then
     raise exception 'Idempotency conflict';
   end if;
   return jsonb_build_object('order_code',existing.order_code,'total',existing.total,'payment_status',existing.payment_status,'order_status',existing.order_status);
 end if;
 if jsonb_array_length(p_items)=0 then raise exception 'Empty cart'; end if;
 insert into public.orders(order_code,telegram_user_id,telegram_username,telegram_verified,customer_language,customer_name,phone,backup_phone,address,comment,total,currency,payment_method,payment_status,order_status,lookup_token_hash,idempotency_key,request_hash)
 values(p_order->>'order_code',p_order->>'telegram_user_id',p_order->>'telegram_username',(p_order->>'telegram_verified')::boolean,coalesce(p_order->>'customer_language','uz'),p_order->>'customer_name',p_order->>'phone',p_order->>'backup_phone',p_order->>'address',p_order->>'comment',(p_order->>'total')::numeric,'USD','manual','awaiting_payment','awaiting_payment',p_order->>'lookup_token_hash',p_order->>'idempotency_key',p_order->>'request_hash') returning * into saved;
